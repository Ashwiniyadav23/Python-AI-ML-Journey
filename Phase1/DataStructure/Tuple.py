# Tuple — like a list, but can't be changed after creation

coordinates = (1,2,3,4,5,6,7)   # e.g. latitude, longitude

# Accessing Elements
result = coordinates[0]
print(result)

# Negative Indexing
print(coordinates[-1])   # -1 means the last element.

# Slicing
print(coordinates[1:4]) # Stop (not included)

